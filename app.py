# ---------------------------------------------------------------------------
# Safety & Guardrail Utilities
# ---------------------------------------------------------------------------

# Patterns that suggest prompt injection or jailbreak attempts
INJECTION_PATTERNS = [
    r"ignore\s+(previous|prior|above|all)\s+instructions",
    r"disregard\s+(previous|prior|above|all)\s+instructions",
    r"forget\s+(previous|prior|above|all)\s+instructions",
    r"reveal\s+(your\s+)?(system\s+)?prompt",
    r"show\s+(me\s+)?(your\s+)?(system\s+)?prompt",
    r"bypass\s+.*?(safety|guardrail|filter|restriction|rule)",
    r"override\s+.*?(safety|guardrail|filter|restriction|rule)",
    r"circumvent\s+.*?(safety|guardrail|filter|restriction|rule)",
    r"you\s+are\s+now\s+",
    r"act\s+as\s+(if\s+you\s+are\s+)?",
    r"\bdan\b",           # "Do Anything Now" jailbreak
    r"jailbreak",
    r"api[\s_-]?key",
    r"groq[\s_-]?key",
    r"secret[\s_-]?key",
    r"expose.*key",
    r"print.*key",
    r"output.*key",
    r"ignore.*safety",
    r"pretend.*no.*restriction",
    r"simulate.*unrestricted",
    r"no\s+restriction",
    r"without\s+(any\s+)?(safety|restriction|filter|guardrail)",
]

_INJECTION_RE = re.compile(
    "|".join(INJECTION_PATTERNS),
    flags=re.IGNORECASE,
)

MAX_INPUT_LENGTH = 1000  # characters


def is_prompt_injection(text: str) -> bool:
    """Return True if the text contains known prompt injection patterns."""
    return bool(_INJECTION_RE.search(text))


def sanitise_input(text: str) -> str:
    """Strip HTML tags, escape special characters, and enforce length limit."""
    # Remove HTML tags
    text = re.sub(r"<[^>]+>", "", text)
    # HTML-escape remaining special chars
    text = html.escape(text)
    # Enforce length
    return text[:MAX_INPUT_LENGTH]


def add_disclaimer(text: str) -> str:
    """Append the medical disclaimer to any response text."""
    return text + MEDICAL_DISCLAIMER


def get_groq_client() -> Groq:
    """Return an authenticated Groq client using the environment variable."""
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise EnvironmentError(
            "GROQ_API_KEY environment variable is not set. "
            "Please configure it in your .env file before running the application."
        )
    return Groq(api_key=api_key)


