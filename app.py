@app.route("/generate_plan", methods=["POST"])
def generate_plan():
    """
    Generate a personalised nutrition plan based on the user's profile.
    Expects JSON: { name, age, diet, medical, city, country }
    """
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"status": "error", "message": "Invalid request body."}), 400

    # Extract and sanitise inputs
    name = sanitise_input(str(data.get("name", "User")))
    age = sanitise_input(str(data.get("age", "")))
    diet = sanitise_input(str(data.get("diet", "")))
    medical = sanitise_input(str(data.get("medical", "None")))
    city = sanitise_input(str(data.get("city", "")))
    country = sanitise_input(str(data.get("country", "")))

    # Basic validation
    if not name or not age or not diet:
        return jsonify({"status": "error", "message": "Name, age, and diet preference are required."}), 400

    # Prompt injection check on all user-supplied fields
    for field_value in [name, age, diet, medical, city, country]:
        if is_prompt_injection(field_value):
            logger.warning("Prompt injection attempt detected in /generate_plan: %s", field_value)
            return jsonify({
                "status": "error",
                "message": "Your input contains content that cannot be processed. Please enter valid profile information."
            }), 400

    # Build the user message
    location_str = f"{city}, {country}" if city and country else (country or city or "Not specified")
    user_message = (
        f"Please create a personalised daily nutrition plan for me.\n\n"
        f"**My Profile:**\n"
        f"- Name: {name}\n"
        f"- Age: {age} years\n"
        f"- Diet Preference: {diet}\n"
        f"- Medical History / Conditions: {medical}\n"
        f"- Location: {location_str}\n\n"
        f"Please provide a detailed daily meal plan (Breakfast, Mid-Morning Snack, Lunch, "
        f"Evening Snack, Dinner) with nutritional notes, tailored to my diet preference, "
        f"health conditions, and locally available foods in my region."
    )

    try:
        client = get_groq_client()
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": PLAN_SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
            temperature=0.7,
            max_tokens=2048,
        )
        plan_text = response.choices[0].message.content
        plan_with_disclaimer = add_disclaimer(plan_text)
        logger.info("Nutrition plan generated for user: %s", name)
        return jsonify({"status": "success", "plan": plan_with_disclaimer})

    except EnvironmentError as e:
        logger.error("Environment configuration error: %s", e)
        return jsonify({"status": "error", "message": str(e)}), 500
    except Exception as e:
        logger.error("Groq API error during plan generation: %s", e)
        return jsonify({
            "status": "error",
            "message": "An error occurred while generating the nutrition plan. Please try again."
        }), 500


@app.route("/chat", methods=["POST"])
def chat():
    """
    Conversational agent endpoint.
    Expects JSON: { message, profile: { name, age, diet, medical, city, country } }
    """
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"status": "error", "message": "Invalid request body."}), 400

    raw_message = str(data.get("message", "")).strip()
    if not raw_message:
        return jsonify({"status": "error", "message": "Message cannot be empty."}), 400

    # Sanitise user message
    user_message = sanitise_input(raw_message)

    # Prompt injection check
    if is_prompt_injection(user_message):
        logger.warning("Prompt injection attempt detected in /chat.")
        return jsonify({
            "status": "success",
            "reply": (
                "I'm sorry, but I can't process that kind of request. "
                "I'm here to help you with nutrition and healthy eating questions. "
                "Please feel free to ask me about meal plans, healthy foods, or dietary tips!"
            )
        })

    # Extract and sanitise profile context (optional, used to personalise chat)
    profile = data.get("profile", {})
    p_name = sanitise_input(str(profile.get("name", "")))
    p_age = sanitise_input(str(profile.get("age", "")))
    p_diet = sanitise_input(str(profile.get("diet", "")))
    p_medical = sanitise_input(str(profile.get("medical", "")))
    p_city = sanitise_input(str(profile.get("city", "")))
    p_country = sanitise_input(str(profile.get("country", "")))

    # Build context string if profile is available
    context_parts = []
    if p_name:
        context_parts.append(f"Name: {p_name}")
    if p_age:
        context_parts.append(f"Age: {p_age} years")
    if p_diet:
        context_parts.append(f"Diet: {p_diet}")
    if p_medical:
        context_parts.append(f"Medical History: {p_medical}")
    if p_city or p_country:
        loc = f"{p_city}, {p_country}".strip(", ")
        context_parts.append(f"Location: {loc}")

    system_content = CHAT_SYSTEM_PROMPT
    if context_parts:
        context_str = "\n".join(context_parts)
        system_content += (
            f"\n\nThe user has provided the following profile for personalised assistance:\n{context_str}\n"
            "Use this profile to personalise your responses where relevant."
        )

    try:
        client = get_groq_client()
        response = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": system_content},
                {"role": "user", "content": user_message},
            ],
            temperature=0.7,
            max_tokens=1024,
        )
        reply_text = response.choices[0].message.content
        reply_with_disclaimer = add_disclaimer(reply_text)
        return jsonify({"status": "success", "reply": reply_with_disclaimer})

    except EnvironmentError as e:
        logger.error("Environment configuration error: %s", e)
        return jsonify({"status": "error", "message": str(e)}), 500
    except Exception as e:
        logger.error("Groq API error during chat: %s", e)
        return jsonify({
            "status": "error",
            "message": "An error occurred while processing your query. Please try again."
        }), 500


